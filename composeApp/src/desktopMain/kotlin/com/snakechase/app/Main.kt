package com.snakechase.app

import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.remember
import androidx.compose.runtime.setValue
import androidx.compose.ui.input.key.Key
import androidx.compose.ui.input.key.KeyEventType
import androidx.compose.ui.input.key.key
import androidx.compose.ui.input.key.type
import androidx.compose.ui.unit.dp
import androidx.compose.ui.window.Window
import androidx.compose.ui.window.WindowPlacement
import androidx.compose.ui.window.application
import androidx.compose.ui.window.rememberWindowState
import com.snakechase.app.di.appModule
import com.snakechase.app.di.platformModule
import org.koin.core.context.startKoin

fun main() {
    startKoin {
        modules(appModule, platformModule)
    }

    application {
        var isFullscreen by remember { mutableStateOf(false) }
        val windowState = rememberWindowState(
            placement = if (isFullscreen) WindowPlacement.Fullscreen else WindowPlacement.Floating,
            width = 1200.dp,
            height = 750.dp,
        )

        Window(
            onCloseRequest = ::exitApplication,
            title = "Snake Chase — KMP Survival",
            // Same mark as the Android icon and the web favicon (generated by tools/generate_icon.py).
            icon = remember {
                Thread.currentThread().contextClassLoader.getResourceAsStream("app_icon.svg")!!.use {
                    androidx.compose.ui.res.loadSvgPainter(it, androidx.compose.ui.unit.Density(1f))
                }
            },
            state = windowState,
            onKeyEvent = { keyEvent ->
                if (keyEvent.type == KeyEventType.KeyDown && keyEvent.key == Key.F11) {
                    isFullscreen = !isFullscreen
                    true
                } else {
                    false
                }
            },
        ) {
            App()
        }
    }
}
