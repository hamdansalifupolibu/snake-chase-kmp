"""Generates the Snake Chase app icon (Android adaptive icon, web favicon, desktop window icon) from code.

The art redraws the glowing beaded snake and food orb from the game's original painting
(bg_landing). Run from anywhere: python tools/generate_icon.py
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "composeApp" / "src"
# Icon from the bg_landing painting: the blue beaded snake chasing the glowing food orb.
def circ(x,y,r): return "M%.2f,%.2fm-%.2f,0a%.2f,%.2f 0,1 1,%.2f 0a%.2f,%.2f 0,1 1,-%.2f 0"%(x,y,r,r,r,2*r,r,r,2*r)
def bez(t,p0,p1,p2,p3):
    u=1-t; return tuple(u*u*u*a+3*u*u*t*b+3*u*t*t*c+t*t*t*d for a,b,c,d in zip(p0,p1,p2,p3))
# snake path: tail bottom-left curling up to the head upper-middle (like the painting's arc)
P0,P1,P2,P3=(30,80),(22,62),(30,40),(50,37)
beads=[]
n=8
for i in range(n):
    t=i/(n-1); x,y=bez(t,P0,P1,P2,P3)
    r=1.7+2.5*t   # tail small -> head big
    beads.append((x,y,r))
head=beads[-1]; hx,hy,hr=head
hr=6.4; hx+=1.0
orb=(70.5,60.0)
glow=lambda x,y,r,a: f'''    <path android:pathData="{circ(x,y,r)}">
        <aapt:attr name="android:fillColor"><gradient android:type="radial" android:centerX="{x:.2f}" android:centerY="{y:.2f}" android:gradientRadius="{r:.2f}" android:startColor="{a}" android:endColor="#000F2CFF" /></aapt:attr>
    </path>'''
core=lambda x,y,r: f'''    <path android:pathData="{circ(x,y,r)}">
        <aapt:attr name="android:fillColor"><gradient android:type="radial" android:centerX="{x-r*0.3:.2f}" android:centerY="{y-r*0.3:.2f}" android:gradientRadius="{r*1.3:.2f}" android:startColor="#FFE9F6FF" android:centerColor="#FF4FA8FF" android:endColor="#FF1A3DFF" /></aapt:attr>
    </path>'''
parts=[]
# a thin light trail through the beads
trail="M"+" L".join("%.2f,%.2f"%(x,y) for x,y,_ in beads)
parts.append(f'    <path android:pathData="{trail}" android:strokeColor="#996FC6FF" android:strokeWidth="1.2" android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000" />')
for x,y,r in beads[:-1]:
    parts.append(glow(x,y,r*2.8,"#8C2F6BFF"))
    parts.append(core(x,y,r))
parts.append(glow(hx,hy,hr*2.0,"#992F6BFF"))
parts.append(core(hx,hy,hr))
# eyes like the painting: two white eyes with dark pupils
for dx in (-2.4,2.4):
    parts.append(f'    <path android:fillColor="#FFFFFFFF" android:pathData="{circ(hx+dx,hy-0.4,1.9)}" />')
    parts.append(f'    <path android:fillColor="#FF0A1030" android:pathData="{circ(hx+dx+0.5,hy-0.2,1.0)}" />')
# food: soft halo ring, glow, bright core, little tail curl like the painting
ox,oy=orb
parts.append(glow(ox,oy,15,"#552F6BFF"))
parts.append(f'    <path android:pathData="{circ(ox,oy,9.5)}" android:strokeColor="#556FC6FF" android:strokeWidth="1" android:fillColor="#00000000" />')
parts.append(f'    <path android:pathData="M{ox:.2f},{oy-3:.2f} C{ox-1:.2f},{oy-9:.2f} {ox+4:.2f},{oy-12:.2f} {ox+2.5:.2f},{oy-7:.2f} C{ox+1:.2f},{oy-3:.2f} {ox-4:.2f},{oy-10:.2f} {ox-8:.2f},{oy-17:.2f}" android:strokeColor="#CC7FD8FF" android:strokeWidth="1.3" android:strokeLineCap="round" android:fillColor="#00000000" />')
parts.append(glow(ox,oy,7,"#CC4FC8FF"))
parts.append(f'''    <path android:pathData="{circ(ox,oy,3.6)}">
        <aapt:attr name="android:fillColor"><gradient android:type="radial" android:centerX="{ox:.2f}" android:centerY="{oy:.2f}" android:gradientRadius="3.6" android:startColor="#FFFFFFFF" android:endColor="#FF5FD6FF" /></aapt:attr>
    </path>''')
fg=f'''<?xml version="1.0" encoding="utf-8"?>
<!--
  Snake Chase icon, drawn from the game's original painting (bg_landing): the glowing blue beaded
  snake curling toward the glowing food orb. Generated by a script; 108dp adaptive-icon canvas.
-->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
{chr(10).join(parts)}
</vector>
'''
grid=[]
for i in range(0,109,12):
    grid.append(f"M{i},0 L{i},108"); grid.append(f"M0,{i} L108,{i}")
bg=f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Night sky to arena floor, with the painting's faint blue grid. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor"><gradient android:type="linear" android:startX="54" android:startY="0" android:endX="54" android:endY="108" android:startColor="#FF1B1540" android:centerColor="#FF0E1030" android:endColor="#FF060818" /></aapt:attr>
    </path>
    <path android:pathData="{' '.join(grid)}" android:strokeColor="#263C6CFF" android:strokeWidth="0.5" android:fillColor="#00000000" />
    <path android:pathData="M54,40m-46,0a46,46 0,1 1,92 0a46,46 0,1 1,-92 0">
        <aapt:attr name="android:fillColor"><gradient android:type="radial" android:centerX="54" android:centerY="30" android:gradientRadius="46" android:startColor="#40FF7A5A" android:endColor="#00FF7A5A" /></aapt:attr>
    </path>
</vector>
'''
mono_parts=[f'    <path android:fillColor="#FFFFFFFF" android:pathData="{circ(x,y,r)}" />' for x,y,r in beads[:-1]]
mono_parts.append(f'    <path android:fillColor="#FFFFFFFF" android:pathData="{circ(hx,hy,hr)}" />')
mono_parts.append(f'    <path android:fillColor="#FFFFFFFF" android:pathData="{circ(ox,oy,4.5)}" />')
mono=f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Single-colour version for Android 13 themed icons. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
{chr(10).join(mono_parts)}
</vector>
'''
base=str(ROOT / "androidMain" / "res" / "drawable") + "/"
for name,txt in (("ic_launcher_foreground.xml",fg),("ic_launcher_background.xml",bg),("ic_launcher_monochrome.xml",mono)):
    open(base+name,"w",encoding="utf-8",newline="").write(txt)
print("ok head",round(hx,1),round(hy,1))
# Web favicon: the same beads and food as SVG.
svgp=[]
svgp.append('<rect x="14" y="14" width="80" height="80" rx="18" fill="url(#bg)"/>')
svgp.append(f'<path d="{trail}" fill="none" stroke="#6FC6FF" stroke-opacity=".6" stroke-width="1.2"/>')
for x,y,r in beads[:-1]:
    svgp.append(f'<circle cx="{x:.2f}" cy="{y:.2f}" r="{r*2.8:.2f}" fill="url(#glow)"/><circle cx="{x:.2f}" cy="{y:.2f}" r="{r:.2f}" fill="url(#bead)"/>')
svgp.append(f'<circle cx="{hx:.2f}" cy="{hy:.2f}" r="{hr*2:.2f}" fill="url(#glow)"/><circle cx="{hx:.2f}" cy="{hy:.2f}" r="{hr:.2f}" fill="url(#bead)"/>')
for dx in (-2.4,2.4):
    svgp.append(f'<circle cx="{hx+dx:.2f}" cy="{hy-0.4:.2f}" r="1.9" fill="#fff"/><circle cx="{hx+dx+0.5:.2f}" cy="{hy-0.2:.2f}" r="1" fill="#0A1030"/>')
svgp.append(f'<circle cx="{ox}" cy="{oy}" r="15" fill="url(#glow)"/><circle cx="{ox}" cy="{oy}" r="9.5" fill="none" stroke="#6FC6FF" stroke-opacity=".35"/><circle cx="{ox}" cy="{oy}" r="3.6" fill="#E9FBFF"/>')
svg=f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="14 14 80 80">
  <!-- Snake Chase mark from the original painting: the glowing beaded snake and the food orb. -->
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#1B1540"/><stop offset=".5" stop-color="#0E1030"/><stop offset="1" stop-color="#060818"/></linearGradient>
    <radialGradient id="glow"><stop offset="0" stop-color="#2F6BFF" stop-opacity=".55"/><stop offset="1" stop-color="#2F6BFF" stop-opacity="0"/></radialGradient>
    <radialGradient id="bead" cx=".35" cy=".35" r=".8"><stop offset="0" stop-color="#E9F6FF"/><stop offset=".5" stop-color="#4FA8FF"/><stop offset="1" stop-color="#1A3DFF"/></radialGradient>
  </defs>
  {chr(10).join("  "+p for p in svgp)}
</svg>
'''
open(ROOT / "wasmJsMain" / "resources" / "favicon.svg","w",encoding="utf-8",newline="").write(svg)
open(ROOT / "desktopMain" / "resources" / "app_icon.svg","w",encoding="utf-8",newline="").write(svg)
print("svg ok")
